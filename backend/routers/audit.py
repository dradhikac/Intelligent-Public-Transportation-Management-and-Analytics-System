"""
TransitIQ API - Audit Trails & Security Compliance Router
Inspects immutable audit logs and triggers activity history.
"""

from fastapi import APIRouter, Query
from typing import Optional
from ..database import fetch_all

router = APIRouter(prefix="/api/audit", tags=["Security & Audit Logs"])


@router.get("/logs")
def get_audit_logs(
    table_name: Optional[str] = None,
    operation: Optional[str] = None,
    limit: int = Query(default=100, le=500)
):
    """
    Queries immutable audit records generated by PostgreSQL trigger trg_audit_*
    and trigger function fn_audit_changes().
    """
    query = """
        SELECT
            audit_id,
            table_name,
            record_id,
            operation,
            old_data,
            new_data,
            changed_at,
            changed_by
        FROM audit_logs
        WHERE 1=1
    """
    params = []
    if table_name:
        query += " AND table_name = %s"
        params.append(table_name)
    if operation:
        query += " AND operation = %s"
        params.append(operation.upper())

    query += " ORDER BY changed_at DESC, audit_id DESC LIMIT %s;"
    params.append(limit)

    return fetch_all(query, tuple(params))
