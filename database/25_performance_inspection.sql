-- =====================================================================
-- PROJECT: TransitIQ – Intelligent Public Transportation Management
-- FILE: database/25_performance_inspection.sql
-- PURPOSE: Step 12 – Database Performance Baseline & Catalog Inspection
-- TARGET DATABASE: transitiq_db (PostgreSQL 14+)
--
-- DESCRIPTION:
--   Comprehensive DBA inspection script gathering baseline metrics across
--   all 17 operational tables: row counts, physical table & index sizes,
--   existing index coverage, dead tuple statistics, and cache hit ratios.
-- =====================================================================

DO $$
BEGIN
    RAISE NOTICE '=====================================================';
    RAISE NOTICE 'TRANSITIQLAB: PERFORMANCE & CATALOG INSPECTION';
    RAISE NOTICE '=====================================================';
END;
$$;

-- =====================================================================
-- 1. OPERATIONAL TABLE INVENTORY, ROW COUNTS & STORAGE FOOTPRINT
-- Purpose: Quantify live row volume and disk consumption per relation.
-- =====================================================================
SELECT
    c.relname AS table_name,
    c.reltuples::BIGINT AS estimated_rows,
    pg_size_pretty(pg_relation_size(c.oid)) AS table_size,
    pg_size_pretty(pg_total_relation_size(c.oid) - pg_relation_size(c.oid)) AS index_size,
    pg_size_pretty(pg_total_relation_size(c.oid)) AS total_size
FROM pg_class c
JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE n.nspname = 'public'
  AND c.relkind = 'r'
  AND c.relname IN (
    'bus_types', 'buses', 'maintenance_records', 'routes', 'stops',
    'route_stops', 'drivers', 'schedules', 'operating_days',
    'schedule_operating_days', 'schedule_stop_times', 'trips',
    'trip_stop_logs', 'passenger_counts', 'delay_reasons',
    'delay_records', 'audit_logs'
  )
ORDER BY pg_total_relation_size(c.oid) DESC;


-- =====================================================================
-- 2. EXISTING INDEX COVERAGE & USAGE STATISTICS
-- Purpose: Inspect all existing indexes, scan counts, and disk footprints.
-- =====================================================================
SELECT
    ui.schemaname,
    ui.relname AS table_name,
    ui.indexrelname AS index_name,
    pg_size_pretty(pg_relation_size(ui.indexrelid)) AS index_size,
    ui.idx_scan AS index_scans_performed,
    ui.idx_tup_read AS tuples_read,
    ui.idx_tup_fetch AS tuples_fetched
FROM pg_stat_user_indexes ui
WHERE ui.schemaname = 'public'
ORDER BY ui.relname, ui.indexrelname;


-- =====================================================================
-- 3. SCAN PROFILE: SEQUENTIAL SCANS VS INDEX SCANS
-- Purpose: Identify tables with high seq_scan counts that may benefit
--          from targeted indexing under scaled production volume.
-- =====================================================================
SELECT
    ut.relname AS table_name,
    ut.seq_scan AS sequential_scans,
    ut.seq_tup_read AS seq_tuples_read,
    ut.idx_scan AS index_scans,
    ut.idx_tup_fetch AS index_tuples_fetched,
    ROUND(
        100.0 * ut.idx_scan / NULLIF(ut.seq_scan + ut.idx_scan, 0),
        2
    ) AS index_scan_ratio_pct
FROM pg_stat_user_tables ut
WHERE ut.schemaname = 'public'
ORDER BY ut.seq_scan DESC;


-- =====================================================================
-- 4. TABLE BLOAT & DEAD TUPLE AUDIT
-- Purpose: Monitor dead tuples generated by UPDATE/DELETE operations
--          to assess autovacuum timeliness and table health.
-- =====================================================================
SELECT
    ut.relname AS table_name,
    ut.n_live_tup AS live_tuples,
    ut.n_dead_tup AS dead_tuples,
    ROUND(
        100.0 * ut.n_dead_tup / NULLIF(ut.n_live_tup + ut.n_dead_tup, 0),
        2
    ) AS dead_tuple_ratio_pct,
    ut.last_vacuum,
    ut.last_autovacuum,
    ut.last_analyze,
    ut.last_autoanalyze
FROM pg_stat_user_tables ut
WHERE ut.schemaname = 'public'
ORDER BY ut.n_dead_tup DESC;


-- =====================================================================
-- 5. BUFFER CACHE HIT RATIO (TABLES & INDEXES)
-- Purpose: Measure percentage of block reads served from memory (RAM)
--          vs physical disk I/O. Goal in production is > 99%.
-- =====================================================================
SELECT
    'Tables' AS object_category,
    ROUND(
        100.0 * SUM(heap_blks_hit) / NULLIF(SUM(heap_blks_hit) + SUM(heap_blks_read), 0),
        2
    ) AS cache_hit_ratio_pct
FROM pg_statio_user_tables
WHERE schemaname = 'public'
UNION ALL
SELECT
    'Indexes' AS object_category,
    ROUND(
        100.0 * SUM(idx_blks_hit) / NULLIF(SUM(idx_blks_hit) + SUM(idx_blks_read), 0),
        2
    ) AS cache_hit_ratio_pct
FROM pg_statio_user_indexes
WHERE schemaname = 'public';


-- =====================================================================
-- 6. AUTOVACUUM GLOBAL & RELATION-LEVEL SETTINGS
-- Purpose: Inspect active autovacuum scale factors and thresholds.
-- =====================================================================
SELECT
    name AS setting_name,
    setting AS current_value,
    unit,
    short_desc AS description
FROM pg_settings
WHERE name IN (
    'autovacuum',
    'autovacuum_vacuum_threshold',
    'autovacuum_vacuum_scale_factor',
    'autovacuum_analyze_threshold',
    'autovacuum_analyze_scale_factor',
    'autovacuum_naptime',
    'autovacuum_max_workers',
    'maintenance_work_mem',
    'shared_buffers'
)
ORDER BY name;
